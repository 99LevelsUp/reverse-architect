//! The map of a module: one line per type, the level above the cards (plan
//! B, U10: R1, R4, R14, AE7, KTD7, KTD8).
//!
//! Navigation starts at a module, not at a full-text search. A module's map
//! answers "which of these types is the one" without opening a card: each
//! row carries the type's kind, a link to its card, its purpose in brief and
//! what sets it apart — the database objects it writes, reads or calls, what
//! it implements or extends, whether it is an entry point. The row repeats no
//! header: the page title names the module and every row inherits it (R4).
//!
//! What a row says is read from the finished card, never from the graph
//! again: the purpose sentence is the card's own ([`super::story::Story::purpose`]),
//! and what sets the type apart is that purpose's structural sentence
//! ([`Claim::Reaches`]) — so a map and a card cannot disagree.
//!
//! - **One row per type with a card**, sorted by name and then identity, so
//!   adding a type moves the rows after it by one and no further.
//! - **Generated types** ([`Card::generated`]) are one row with their count,
//!   last: a designer file's forty controls are not forty things a reader
//!   chooses between. A type with one hand-written part — a form's own
//!   `Form1.cs` beside its `Form1.Designer.cs` — is hand-written and keeps
//!   its row.
//! - **A row stays within [`MAP_ROW_BYTES`]** (Success Criteria): the kind and
//!   the link always; then what sets the type apart, each entry naming two
//!   objects, or one where two do not fit, beside a reserve for the purpose;
//!   then the purpose, cut at a word to what the row has left. A row whose
//!   kind and link alone are longer stays whole — a link cannot be cut.
//! - **A large map is cut into `## Part N`** by the same greedy packing as a
//!   detail ([`fixed_partition`], KTD8), on its own threshold counted in rows
//!   ([`MAP_PART_ROWS`]); every row is one unit, so no type is ever dropped
//!   or split.
//!
//! A module with no type card has no map; its card holds its files.

