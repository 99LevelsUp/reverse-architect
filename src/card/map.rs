/// The most bytes one map row may take, its line break included (plan B,
/// Success Criteria: some fifty tokens). See the module doc for what gives
/// way first.
pub const MAP_ROW_BYTES: usize = 200;

/// How many rows a map holds before it is cut into parts (KTD8: the map's own
/// threshold, in rows). A part is what one chunk of the manifest carries; at
/// most [`MAP_ROW_BYTES`] a row, fifty rows stay within some ten kilobytes —
/// the size of a large detail part ([`super::detail::DETAIL_PART_BYTES`]) —
/// and are usually well under it.
pub const MAP_PART_ROWS: usize = 50;

/// How many objects or bases one entry of a row names before `+N`.
const NAMED_IN_ROW: usize = 2;

/// The bytes a row keeps for the purpose before it takes what sets the type
/// apart: enough for the gist of a sentence, so a type that writes many
/// tables does not lose what it is for.
const PURPOSE_RESERVE: usize = 40;

/// A purpose cut shorter than this is no gist; the row leaves it out.
const PURPOSE_MIN: usize = 16;

/// Between the link and the purpose.
const PURPOSE_SEP: &str = " — ";
/// Between the entries of a row.
const ENTRY_SEP: &str = " · ";

/// The type cards of every module that has one, by module: the modules that
/// get a map, and the cards each map lists, in card order.
pub(super) fn modules_with_types(cards: &[Card]) -> BTreeMap<&str, Vec<&Card>> {
    let mut by_module: BTreeMap<&str, Vec<&Card>> = BTreeMap::new();
    for card in cards.iter().filter(|c| c.kind == CardKind::Type) {
        if let Some(module) = card.story.module.as_deref() {
            by_module.entry(module).or_default().push(card);
        }
    }
    by_module
}

/// The files whose own comment says a tool wrote them: a comment anchor
/// outside every declaration that holds `<auto-generated` — the header
/// Visual Studio and the .NET generators write above the code. Read from the
/// anchors the lexer already keeps (plan B, U3), so no new fact is needed.
pub(super) fn marked_generated<'a>(nodes: &BTreeMap<&'a str, &'a Node>) -> HashSet<&'a str> {
    nodes
        .iter()
        .filter(|(_, node)| node.kind == NodeKind::File)
        .filter(|(_, node)| {
            node.facts.iter().any(|f| match (&f.kind, &f.value) {
                (FactKind::Anchor, FactValue::Text(value)) => AnchorText::decode(value)
                    .is_some_and(|anchor| {
                        const MARK: &[u8] = b"<auto-generated";
                        anchor.source == AnchorSource::Comment
                            && anchor
                                .text
                                .as_bytes()
                                .windows(MARK.len())
                                .any(|w| w.eq_ignore_ascii_case(MARK))
                    }),
                _ => false,
            })
        })
        .map(|(key, _)| *key)
        .collect()
}

/// Whether every part of the type `node` sits in a generated file — by its
/// name, or by the header comment of [`marked_generated`]. The parts are the
/// files its declaration facts were read from, a `partial` type's every one.
pub(super) fn generated_type(node: &Node, marked: &HashSet<&str>) -> bool {
    let mut parts = node
        .facts
        .iter()
        .filter(|f| {
            matches!(
                f.kind,
                FactKind::SymbolName | FactKind::SymbolKind | FactKind::SymbolSignature
            )
        })
        .flat_map(|f| {
            std::iter::once(f.provenance.file.as_str())
                .chain(f.dissent.iter().map(|c| c.provenance.file.as_str()))
        })
        .peekable();
    parts.peek().is_some() && parts.all(|file| is_generated_path(file) || marked.contains(file))
}

/// The map of every module that has one, as corpus-relative files ready to
/// write, in card order. Each renders from its module's cards and the
/// read-only index alone, so they render in parallel.
pub fn render_map_files(
    cards: &[Card],
    index: &CardIndex,
    lang: Lang,
    links: LinkStyle,
) -> Vec<RenderedFile> {
    use rayon::prelude::*;
    let by_module = modules_with_types(cards);
    cards
        .par_iter()
        .filter_map(|module| {
            let path = module.map.as_deref()?;
            let types = by_module.get(module.identity.as_str())?;
            Some(RenderedFile {
                path: path.to_string(),
                contents: render_map(module, types, lang, links, index),
            })
        })
        .collect()
}

/// One module's map.
fn render_map(
    module: &Card,
    types: &[&Card],
    lang: Lang,
    links: LinkStyle,
    index: &CardIndex,
) -> String {
    let from = module.map.as_deref().unwrap_or(&module.path);
    let cs = lang == Lang::Cs;
    let label = match (module.identity.as_str(), cs) {
        (".", true) => "(kořen repozitáře)",
        (identity, _) => module_label(identity),
    };

    let mut s = format!(
        "---\nschema: {CARD_SCHEMA_VERSION}\ntool: reverse-architect\nkind: map\nof: {}\n---\n\n# {label}\n\n",
        module.kind_word
    );
    // The header every row inherits (R4): which module, the way to its card,
    // how many types.
    let count = if cs {
        cs_n(types.len(), ("typ", "typy", "typů"))
    } else {
        plural(types.len(), "type", "types")
    };
    let _ = writeln!(
        s,
        "**{}** · {} · {count}\n",
        if cs { "mapa modulu" } else { "module map" },
        link(from, &module.path, label, links),
    );
    s.push_str(if cs {
        "Jeden řádek na každý typ modulu: druh, karta, účel ve zkratce a čím se typ liší — \
         databázové objekty, do kterých zapisuje (`writes`), které čte (`reads`) nebo volá \
         (`calls`), co implementuje nebo rozšiřuje a zda je vstupním bodem.\n"
    } else {
        "One row per type of the module: its kind, its card, its purpose in brief and what sets \
         it apart — the database objects it `writes`, `reads` or `calls`, what it implements or \
         extends, and whether it is an entry point.\n"
    });

    let mut named: Vec<&Card> = types.iter().copied().filter(|c| !c.generated).collect();
    named.sort_by(|a, b| (&a.title, &a.identity).cmp(&(&b.title, &b.identity)));
    let mut rows: Vec<String> = named
        .iter()
        .map(|card| row(card, from, lang, links, index))
        .collect();
    let generated = types.len() - named.len();
    if generated > 0 {
        rows.push(generated_row(generated, lang));
    }

    if rows.len() <= MAP_PART_ROWS {
        s.push_str("\n## Types\n\n");
        rows.iter().for_each(|r| s.push_str(r));
        return s;
    }
    let parts = fixed_partition(rows.iter(), MAP_PART_ROWS, &mut Rows(0));
    for (n, part) in parts.iter().enumerate() {
        let _ = write!(s, "\n## Part {}\n\n", n + 1);
        part.iter().for_each(|r| s.push_str(r));
    }
    s
}

/// The rows of a rendered map, without their line breaks: every line opening
/// with `- ` below its first `##` heading (`## Types` or `## Part 1`). Read
/// back here, beside [`render_map`], so what counts as a row is decided where
/// a row is written — coverage measures them (plan B, U12: KTD13).
pub fn rows(map: &str) -> impl Iterator<Item = &str> {
    map.lines()
        .skip_while(|l| !l.starts_with("## "))
        .filter(|l| l.starts_with("- "))
}

/// A part's weight in rows.
struct Rows(usize);

impl<T> ChunkWeight<T> for Rows {
    fn peek(&self, _: &T) -> usize {
        self.0 + 1
    }
    fn add(&mut self, _: &T) {
        self.0 += 1;
    }
    fn reset(&mut self) {
        self.0 = 0;
    }
}

/// The one row the generated types of a module share.
fn generated_row(n: usize, lang: Lang) -> String {
    match lang {
        Lang::En => format!(
            "- {} (designer or tool output, by file name or header) — no row of their own\n",
            plural(n, "generated type", "generated types")
        ),
        Lang::Cs => format!(
            "- {} (výstup návrháře nebo nástroje podle jména či hlavičky souboru) — bez \
             vlastních řádků\n",
            cs_n(
                n,
                ("generovaný typ", "generované typy", "generovaných typů")
            )
        ),
    }
}

/// One type's row: `- <kind> <card link> — <purpose> · <what sets it apart>`,
/// within [`MAP_ROW_BYTES`] wherever the kind and the link leave room.
fn row(card: &Card, from: &str, lang: Lang, links: LinkStyle, index: &CardIndex) -> String {
    let head = format!(
        "- {} {}",
        kind_word(card),
        mention(from, &card.identity, &card.title, links, index)
    );
    let (purpose, entries) = gist(card, lang);

    // What sets the type apart, in order of how much it tells, as far as the
    // row has room beside the purpose's reserve: an entry names as many
    // objects as fit, down to one, or stays out.
    let reserve = purpose
        .as_ref()
        .map_or(0, |p| PURPOSE_SEP.len() + p.len().min(PURPOSE_RESERVE));
    let mut used = head.len() + 1 + reserve;
    let mut kept: Vec<String> = Vec::new();
    for entry in &entries {
        let fitting = (1..=NAMED_IN_ROW)
            .rev()
            .map(|named| entry.text(named))
            .find(|text| used + ENTRY_SEP.len() + text.len() <= MAP_ROW_BYTES);
        if let Some(text) = fitting {
            used += ENTRY_SEP.len() + text.len();
            kept.push(text);
        }
    }
    let tail: usize = kept.iter().map(|e| ENTRY_SEP.len() + e.len()).sum();

    let mut s = head;
    if let Some(purpose) = purpose {
        let room = MAP_ROW_BYTES.saturating_sub(s.len() + 1 + tail + PURPOSE_SEP.len());
        if let Some(cut) = fit(&purpose, room) {
            s.push_str(PURPOSE_SEP);
            s.push_str(&cut);
        }
    }
    for entry in kept {
        s.push_str(ENTRY_SEP);
        s.push_str(&entry);
    }
    s.push('\n');
    s
}

/// The kind as the signature states it, with the one modifier of each kind
/// that changes what a type is used as — `static class`, `abstract class` —
/// and without access, which the map does not choose by.
fn kind_word(card: &Card) -> String {
    match &card.header {
        Some(header) => {
            let mut words: Vec<&str> = header
                .modifiers
                .iter()
                .map(String::as_str)
                .filter(|m| matches!(*m, "static" | "abstract"))
                .collect();
            words.push(&header.kind);
            words.join(" ")
        }
        None => card.entity_kind.clone().unwrap_or_else(|| "type".into()),
    }
}

/// The row's purpose and its entries, read from the card's purpose.
///
/// The purpose is the first sentence that says what the type IS: the
/// comment's, or the stereotype's. The sentence of kind and member counts is
/// left out — the row states the kind already, and a count is no purpose
/// (R6: say only what is known). The entries are the structural sentence's
/// facts, fact vocabulary in either language: `writes`, `implements`,
/// `extends`, `entry point`, `calls`, `reads`. "Mentions" is no entry — it
/// says only that the code names an object.
fn gist(card: &Card, lang: Lang) -> (Option<String>, Vec<Entry>) {
    let purpose = brief_purpose(card);
    let mut entries: Vec<Entry> = Vec::new();
    let reaches = card.story.purpose.iter().find_map(|s| match &s.claim {
        Claim::Reaches { bases, db, .. } => Some((bases, db)),
        _ => None,
    });
    let access = |kind: DbAccessKind| {
        reaches.and_then(|(_, db)| {
            db.iter()
                .find(|(a, _, _)| *a == kind)
                .map(|(_, objects, total)| Entry {
                    verb: kind.word(),
                    names: objects.clone(),
                    total: *total,
                })
        })
    };
    let based = |word: BaseWord, verb: &'static str| {
        reaches.and_then(|(bases, _)| {
            let names: Vec<String> = bases
                .iter()
                .filter(|(_, w)| *w == word)
                .map(|(label, _)| label.clone())
                .collect();
            (!names.is_empty()).then_some(Entry {
                verb,
                total: names.len(),
                names,
            })
        })
    };
    // An entry point the purpose sentence does not already say.
    let entry = card
        .story
        .purpose
        .iter()
        .any(|s| matches!(s.claim, Claim::EntryPoint { .. }))
        && !purpose.is_some_and(|s| matches!(s.claim, Claim::EntryPoint { .. }));
    entries.extend(access(DbAccessKind::Writes));
    entries.extend(based(BaseWord::Implements, "implements"));
    entries.extend(based(BaseWord::Extends, "extends"));
    if entry {
        entries.push(Entry {
            verb: "entry point",
            names: Vec::new(),
            total: 0,
        });
    }
    entries.extend(access(DbAccessKind::Calls));
    entries.extend(access(DbAccessKind::Reads));
    (purpose.map(|s| s.text(lang)), entries)
}

/// The sentence of the card's purpose that says what the type IS — its
/// comment's, or the stereotype's — or `None` when the purpose has none.
/// The map row's purpose, and the purpose of the manifest's header (plan B,
/// R4), so a row and a header cannot disagree.
pub(super) fn brief_purpose(card: &Card) -> Option<&Sentence> {
    card.story.purpose.iter().find(|s| {
        matches!(
            s.claim,
            Claim::Comment(_)
                | Claim::EntryPoint { .. }
                | Claim::Factory { .. }
                | Claim::StaticHelper { .. }
                | Claim::DataStructure { .. }
        )
    })
}

/// One thing that sets a type apart on its row: a fact word and the names
/// it applies to, of `total` in all.
struct Entry {
    verb: &'static str,
    names: Vec<String>,
    total: usize,
}

impl Entry {
    /// `writes `dba.a`, `dba.b` +3` — the verb, the first `named` names as
    /// code, and `+N` for the rest of the total.
    fn text(&self, named: usize) -> String {
        if self.names.is_empty() {
            return self.verb.to_string();
        }
        format!("{} {}", self.verb, names(&self.names, named, self.total))
    }
}

/// The first `named` of `items` as code, and `+N` for the rest of `total`.
fn names(items: &[String], named: usize, total: usize) -> String {
    let shown: Vec<String> = items.iter().take(named).map(|n| code(n)).collect();
    let rest = total.saturating_sub(shown.len());
    let mut s = shown.join(", ");
    if rest > 0 {
        let _ = write!(s, " +{rest}");
    }
    s
}

/// `text` within `room` bytes: whole when it fits, otherwise cut at the last
/// word that fits with `…` after it, never inside a code span. `None` when
/// what would be left is shorter than [`PURPOSE_MIN`].
fn fit(text: &str, room: usize) -> Option<String> {
    if text.len() <= room {
        return Some(text.to_string());
    }
    const ELLIPSIS: &str = "…";
    let budget = room.checked_sub(ELLIPSIS.len())?;
    let mut end = budget.min(text.len());
    while !text.is_char_boundary(end) {
        end -= 1;
    }
    let mut cut = &text[..end];
    // At a word boundary, unless the first word alone is longer.
    if let Some(space) = cut.rfind(' ') {
        cut = &cut[..space];
    }
    // A code span left open would swallow the rest of the row.
    if cut.matches('`').count() % 2 == 1 {
        cut = &cut[..cut.rfind('`').unwrap_or(0)];
    }
    let cut = cut.trim_end_matches([' ', ',', ';', ':', '.', '—', '-']);
    (cut.len() >= PURPOSE_MIN).then(|| format!("{cut}{ELLIPSIS}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_purpose_that_fits_is_kept_whole() {
        assert_eq!(
            fit("Restores a backup.", 40).as_deref(),
            Some("Restores a backup.")
        );
    }

    #[test]
    fn a_long_purpose_is_cut_at_a_word_and_never_inside_a_code_span() {
        let text = "Creates its own instances through the static method `FromConfiguration`.";
        let cut = fit(text, 64).expect("room enough for a gist");
        assert!(cut.len() <= 64, "{cut}");
        assert_eq!(cut, "Creates its own instances through the static method…");
        assert_eq!(fit(text, 10), None);
    }

    #[test]
    fn a_name_list_names_two_and_counts_the_rest() {
        let items: Vec<String> = ["dba.a", "dba.b", "dba.c"].map(String::from).to_vec();
        assert_eq!(names(&items, 2, 5), "`dba.a`, `dba.b` +3");
        assert_eq!(names(&items, 1, 5), "`dba.a` +4");
        assert_eq!(names(&items[..1], 2, 1), "`dba.a`");
    }
}
